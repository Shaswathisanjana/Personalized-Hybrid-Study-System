import json
from urllib.parse import urlencode
from urllib.request import Request, urlopen

from app.learning_agent.resources.difficulty_estimator import (
    ResourceDifficultyEstimator,
)

from app.learning_agent.resources.models import (
    LearningResource,
)


class WikipediaResourceRetriever:
    """
    Retrieve real Wikipedia articles using MediaWiki search.

    URLs are returned by Wikipedia's API rather than
    generated by an LLM.
    """

    API_URL = "https://en.wikipedia.org/w/api.php"

    def __init__(self, difficulty_estimator=None):
        self.difficulty_estimator = (
            difficulty_estimator
            if difficulty_estimator is not None
            else ResourceDifficultyEstimator()
        )

    def search(
        self,
        concept_name,
        max_results=10,
        target_level=None,
    ):
        if not isinstance(concept_name, str) or not concept_name.strip():
            raise ValueError("concept_name cannot be empty.")

        if max_results <= 0:
            raise ValueError("max_results must be greater than zero.")

        params = {
            "action": "query",
            "generator": "search",
            "gsrsearch": concept_name.strip(),
            "gsrlimit": min(max_results, 20),
            "prop": "info|extracts|pageprops",
            "inprop": "url",
            "exintro": 1,
            "explaintext": 1,
            "exchars": 350,
            "format": "json",
            "formatversion": "2",
        }

        url = self.API_URL + "?" + urlencode(params)

        request = Request(
            url,
            headers={
                "User-Agent": (
                    "CACMPHSS-LearningResearchPrototype/1.0 "
                    "(educational resource retrieval)"
                ),
                "Accept": "application/json",
            },
        )

        try:
            with urlopen(request, timeout=12) as response:
                data = json.load(response)

        except Exception as exc:
            raise RuntimeError(
                f"Wikipedia retrieval failed: {exc}"
            ) from exc

        pages = data.get("query", {}).get("pages", [])

        resources = []

        for page in pages:
            # Wikipedia explicitly marks disambiguation pages.
            if "disambiguation" in page.get("pageprops", {}):
                continue

            title = str(page.get("title", "")).strip()
            article_url = str(page.get("fullurl", "")).strip()
            description = str(page.get("extract", "")).strip()

            if not title or not article_url:
                continue

            if not article_url.startswith(
                "https://en.wikipedia.org/wiki/"
            ):
                continue

            difficulty = self.difficulty_estimator.estimate(
                title=title,
                description=description,
            )

            resources.append(
                LearningResource(
                    title=title,
                    url=article_url,
                    resource_type="article",
                    description=description,
                    source="Wikipedia",
                    difficulty=difficulty,
                    topics=[concept_name.strip()],
                )
            )

        return resources

